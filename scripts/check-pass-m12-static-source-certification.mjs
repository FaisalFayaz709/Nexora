import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const startedAt = new Date().toISOString();

// Keep this aggregate bounded: these gates are intentionally high-level and internally
// cover the lower module/domain gates where needed. Running every low-level gate here
// creates repeated nested executions and is too slow for an offline source pass.
const gates = [
  ['architecture', 'scripts/check-architecture.mjs'],
  ['contracts', 'scripts/check-contracts.mjs'],
  ['database-schema-migrations', 'scripts/check-prisma-schema-migrations.mjs'],
  ['documentation-source-reconciliation', 'scripts/check-docs-source-reconciliation.mjs'],
  ['final-runtime-core-controls-static', 'scripts/check-final-runtime-core-controls.mjs'],
];

const results = [];
for (const [name, script] of gates) {
  const scriptPath = join(root, script);
  if (!existsSync(scriptPath)) {
    results.push({ name, script, status: 'failed', exitCode: 1, stdout: '', stderr: `Missing gate script: ${script}` });
    continue;
  }
  const run = spawnSync(process.execPath, [script], {
    cwd: root,
    encoding: 'utf8',
    env: { ...process.env, NEXORA_STATIC_SOURCE_CERTIFICATION: '1' },
    maxBuffer: 1024 * 1024 * 20,
  });
  results.push({
    name,
    script,
    status: run.status === 0 ? 'passed' : 'failed',
    exitCode: run.status,
    stdout: run.stdout.trim(),
    stderr: run.stderr.trim(),
  });
}

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const lockfileExists = existsSync(join(root, 'pnpm-lock.yaml'));
const finalSh = existsSync(join(root, 'scripts/final-certify.sh')) ? readFileSync(join(root, 'scripts/final-certify.sh'), 'utf8') : '';
const blockedRuntime = [];
if (!lockfileExists) {
  blockedRuntime.push('M1 remains blocked: pnpm-lock.yaml is absent, so frozen install, dependency-backed lint/typecheck/test/build, Prisma CLI runtime, Docker build and full runtime certification are not claimed in this pass.');
}
for (const marker of ['pnpm install --frozen-lockfile', 'pnpm test', 'pnpm db:validate', 'pnpm build']) {
  if (!finalSh.includes(marker)) blockedRuntime.push(`Final certification script missing runtime marker: ${marker}`);
}

const failed = results.filter((result) => result.status !== 'passed');
const payload = {
  gate: 'pass-m12-static-source-certification',
  pass: 'M12',
  title: 'Static Source Certification Aggregate',
  startedAt,
  completedAt: new Date().toISOString(),
  packageManager: pkg.packageManager,
  lockedStack: 'Next.js + TypeScript frontend, Fastify + TypeScript backend, PostgreSQL + Prisma, MinIO, Redis, BullMQ, Docker Compose, Nginx, GitHub Actions',
  certificationScope: 'Zero-dependency static/source aggregate gates only. Does not claim dependency-backed build/test/runtime certification.',
  lowerGateCoverageNote: 'final-runtime-core-controls-static invokes operations-platform, security-hardening, full-workflow-e2e, production-release and runtime-readiness; those gates in turn cover procurement, approvals, projects, assets, field service, maintenance, finance, commercial extensions, portals, reporting, import, SaaS, commercial MVP addendum controls and route coverage.',
  lockfileExists,
  m1Status: lockfileExists ? 'READY_FOR_FROZEN_INSTALL' : 'BLOCKED_WAITING_FOR_REAL_PNPM_LOCKFILE',
  total: results.length,
  passed: results.length - failed.length,
  failed: failed.length,
  blockedRuntime,
  results,
};
mkdirSync(join(root, 'certification-output'), { recursive: true });
writeFileSync(join(root, 'certification-output/pass-m12-static-source-certification.json'), `${JSON.stringify(payload, null, 2)}\n`);

if (failed.length > 0) {
  console.error('PASS M12 static source certification FAILED');
  for (const result of failed) {
    console.error(`- ${result.name}: ${result.stderr || result.stdout || 'no output'}`);
  }
  process.exit(1);
}

console.log(`PASS M12 static source certification PASSED: ${payload.passed}/${payload.total} aggregate static/source gates passed.`);
if (!lockfileExists) {
  console.log('Runtime/dependency certification remains blocked until a real pnpm-lock.yaml is generated by Pass M1 on an online machine.');
}
